/**
 * Turn the Markdown topic pages (grammar/<lang>/*.md) into a typed module,
 * src/generated/grammar.ts, and the exam banks (exam/<id>/*.json) into src/generated/exam.ts,
 * which src/index.ts re-exports. Runs before `tsc` in build, typecheck
 * and test (Node strips the types of this file and of ../src/parse.ts).
 *
 * Usage: node scripts/generate.ts
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseTopic, type GrammarTopic } from "../src/parse.ts";
import { EXAM_PARTS, parseExamBank, type ExamBank, type ExamPart } from "../src/exam.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const grammarDir = join(root, "grammar");

const topics: GrammarTopic[] = [];
for (const lang of readdirSync(grammarDir).sort()) {
  for (const file of readdirSync(join(grammarDir, lang)).sort()) {
    if (!file.endsWith(".md")) continue;
    topics.push(parseTopic(readFileSync(join(grammarDir, lang, file), "utf8"), file, lang));
  }
}

/** Write a generated module only on change, so watchers and incremental builds stay quiet. */
function writeIfChanged(out: string, body: string) {
  mkdirSync(dirname(out), { recursive: true });
  let previous = "";
  try {
    previous = readFileSync(out, "utf8");
  } catch {
    // first run
  }
  if (previous !== body) writeFileSync(out, body);
}

const out = join(root, "src", "generated", "grammar.ts");
const body =
  "// Generated by scripts/generate.ts from grammar/**/*.md. Do not edit.\n" +
  'import type { GrammarTopic } from "../parse.js";\n\n' +
  `export const TOPICS: readonly GrammarTopic[] = ${JSON.stringify(topics, null, 2)};\n`;
writeIfChanged(out, body);

// Exam banks: exam/<exam id>/<part>.json, validated (ids, answers, grammar links).
const examDir = join(root, "exam");
const grammarIds = new Set(topics.map((t) => t.id));
const banks: ExamBank[] = [];
for (const id of readdirSync(examDir).sort()) {
  const files = Object.fromEntries(
    EXAM_PARTS.map((part) => [
      part,
      JSON.parse(readFileSync(join(examDir, id, `${part}.json`), "utf8")),
    ]),
  ) as Record<ExamPart, unknown>;
  banks.push(parseExamBank(id, files, grammarIds));
}
writeIfChanged(
  join(root, "src", "generated", "exam.ts"),
  "// Generated by scripts/generate.ts from exam/**/*.json. Do not edit.\n" +
    'import type { ExamBank } from "../exam.js";\n\n' +
    `export const BANKS: readonly ExamBank[] = ${JSON.stringify(banks, null, 2)};\n`,
);
console.log(`@app/content: ${topics.length} grammar topics, ${banks.length} exam banks`);
