/**
 * Turn the Markdown topic pages (grammar/<lang>/*.md) into a typed module,
 * src/generated/grammar.ts, which src/index.ts re-exports. Runs before `tsc` in build, typecheck
 * and test (Node strips the types of this file and of ../src/parse.ts).
 *
 * Usage: node scripts/generate.ts
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseTopic, type GrammarTopic } from "../src/parse.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const grammarDir = join(root, "grammar");

const topics: GrammarTopic[] = [];
for (const lang of readdirSync(grammarDir).sort()) {
  for (const file of readdirSync(join(grammarDir, lang)).sort()) {
    if (!file.endsWith(".md")) continue;
    topics.push(parseTopic(readFileSync(join(grammarDir, lang, file), "utf8"), file, lang));
  }
}

const out = join(root, "src", "generated", "grammar.ts");
mkdirSync(dirname(out), { recursive: true });
const body =
  "// Generated by scripts/generate.ts from grammar/**/*.md. Do not edit.\n" +
  'import type { GrammarTopic } from "../parse.js";\n\n' +
  `export const TOPICS: readonly GrammarTopic[] = ${JSON.stringify(topics, null, 2)};\n`;
let previous = "";
try {
  previous = readFileSync(out, "utf8");
} catch {
  // first run
}
// Rewrite only on change, so watchers and incremental builds stay quiet.
if (previous !== body) writeFileSync(out, body);
console.log(`@app/content: ${topics.length} grammar topics`);
